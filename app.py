import os

import numpy as np
import streamlit as st
import matplotlib.pyplot as plt
import colormaps as cmaps

st.set_page_config(
    page_title="Cattlelogue",
    page_icon="🐄",
    layout="wide"
)

def main():
    global results_container, vis_type, year, year_range, year_range_window
    st.write("# Cattlelogue")

    results_container = st.empty()
    if not st.session_state.get("show_results", False):
        with results_container.container():
            st.write("""
            ### Mapping Tomorrow's Harvest
            This tool displays outputs from the Cattlelogue model, a proof-of-concept projection
            model for cattle distribution. It uses a hybrid machine-learning approach (AdaBoost/U-Net) informed by
            climate variables and human infrastructure.

            #### Model Architecture
            """)
            st.image("https://github.com/user-attachments/assets/cbeead42-432b-441e-aee5-a47ca61d9347")

    st.divider()
    st.image("logo.jpg", width=200)

    with st.sidebar:
        st.write("## Visualization Settings")
        st.selectbox("Scenario", ["SSP4"])
        vis_type = st.radio("Visualization Type", ["Single Year", "Delta"], index=1)
        if vis_type == "Single Year":
            year = st.slider("Year", min_value=2015, max_value=2100, value=2080)
        else:
            year_range = st.slider("Year Range", min_value=2015, max_value=2100, value=(2020, 2095))
            year_range_window = st.slider("Averaging Window (Years)", min_value=1, max_value=20, value=5)
            if year_range[1]-year_range[0] < year_range_window:
                st.warning(f"The minimum range width must be at least {year_range_window}.")
        if st.button("Generate Visualizations", type="primary", width="stretch"):
            st.session_state.show_results = True

    if st.session_state.get("show_results", False):
        visualize()

def visualize():
    if vis_type == "Single Year":
        visualize_single_year()
    elif vis_type == "Delta":
        visualize_range()

def visualize_single_year():
    global results_container
    OUTPUT_DIR = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "cattlelogue/outputs"
    )

    outputs = []
    for prefix in ["livestock", "crops", "pasture"]:
        output_path = os.path.join(OUTPUT_DIR, f"{prefix}_{year}.npy")
        data = np.load(output_path)
        if data.shape == (1080, 2160):
            data = data[::2, ::2]

        land_mask = data != -1
        data_masked = np.ma.masked_where(~land_mask, data)
        data_values = data_masked.compressed()
        color_limit = (
            np.percentile(data_values, 99) if data_values.size else 0
        )
        if color_limit == 0:
            color_limit = np.max(data_values) if data_values.size else 1

        fig, ax = plt.subplots(figsize=(12, 6))
        image = ax.imshow(
            data_masked,
            cmap="plasma",
            vmin=0,
            vmax=color_limit,
            interpolation="nearest",
            zorder=10,
        )
        ax.xaxis.set_ticklabels([])
        ax.yaxis.set_ticklabels([])
        ax.set_xticks(np.linspace(0, data_masked.shape[1], 36))
        ax.set_yticks(np.linspace(0, data_masked.shape[0], 18))
        ax.grid(axis="both", color="#ddd", linestyle="--", linewidth=0.5, zorder=0)
        for tick in ax.xaxis.get_major_ticks():
            tick.tick1line.set_visible(False)
            tick.tick2line.set_visible(False)
            tick.label1.set_visible(False)
            tick.label2.set_visible(False)
        for tick in ax.yaxis.get_major_ticks():
            tick.tick1line.set_visible(False)
            tick.tick2line.set_visible(False)
            tick.label1.set_visible(False)
            tick.label2.set_visible(False)
        im_ratio = data.shape[0] / data.shape[1]
        fig.colorbar(
            image,
            ax=ax,
            label="Projected Value",
            fraction=0.047 * im_ratio,
        )
        outputs.append(fig)

    results_container.empty()
    with results_container.container():
        st.write(
            f"Projected variables for {year}. Machine learning outputs may be unstable."
        )
        st.write(
            "### Livestock Distribution\n"
            "Values displayed are arbitrary units of model confidence for "
            "livestock suitability."
        )
        st.pyplot(outputs[0])

        st.write(
            "### Intermediate Outputs\n"
            "#### Crop Distribution\n"
            "Values displayed are percentage of land covered by cropland. "
            # "This intermediate output is generated by an AdaBoost model."
        )
        st.pyplot(outputs[1])
        st.write(
            "#### Pasture Distribution\n"
            "Values displayed are percentage of land covered by pasture. "
            # "This intermediate output is generated by an AdaBoost model."
        )
        st.pyplot(outputs[2])

    for output in outputs:
        plt.close(output)

def visualize_range():
    global results_container
    year_start, year_end = year_range
    window = year_range_window
    OUTPUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cattlelogue/outputs")

    outputs = []

    for prefix in ["livestock", "crops", "pasture"]:
        year_start_fnames = [
            os.path.join(OUTPUT_DIR, f"{prefix}_{year}.npy") for year in range(year_start, year_start + window)
        ]
        year_end_fnames = [
            os.path.join(OUTPUT_DIR, f"{prefix}_{year}.npy") for year in range(year_end - window + 1, year_end + 1)
        ]

        year_start_datas = [
            np.load(fname) for fname in year_start_fnames
        ]
        year_end_datas = [
            np.load(fname) for fname in year_end_fnames
        ]
        for i, x in enumerate(year_start_datas):
            if x.shape == (1080, 2160):
                year_start_datas[i] = x[::2,::2]
        for i, x in enumerate(year_end_datas):
            if x.shape == (1080, 2160):
                year_end_datas[i] = x[::2,::2]
        delta = np.mean(year_end_datas, axis=0) - np.mean(year_start_datas, axis=0)
        #smooth/blur delta
        #delta = cv2.GaussianBlur(delta, (7, 7), 0)

        # hack for masking land areas
        # glw4_data = load_glw4_data(resolution=1)
        land_mask = year_start_datas[0] != -1 # glw4_data[0] >= 0
        delta_masked = np.ma.masked_where(~land_mask, delta)
        delta_values = np.abs(delta_masked.compressed())
        color_limit = np.percentile(delta_values, 95) * 1.5 if delta_values.size else 0
        if color_limit == 0:
            color_limit = np.max(delta_values) if delta_values.size else 1

        fig, ax = plt.subplots(figsize=(12, 6))
        # plt.rcParams.update({"font.family": "Segoe UI", "font.size": 8})
        # ax.set_title(
        #     f"Change in {prefix} distribution | {year_start}-{year_end}",
        #     weight="bold",
        # )
        image = ax.imshow(
            delta_masked,
            cmap=cmaps.pride[::-1],
            vmin=-color_limit,
            vmax=color_limit,
            interpolation="nearest",
            zorder=10,
        )
        ax.xaxis.set_ticklabels([])
        ax.yaxis.set_ticklabels([])
        ax.set_xticks(np.linspace(0, delta_masked.shape[1], 36))
        ax.set_yticks(np.linspace(0, delta_masked.shape[0], 18))
        ax.grid(axis="both", color="#ddd", linestyle="--", linewidth=0.5, zorder=0)
        for tick in ax.xaxis.get_major_ticks():
            tick.tick1line.set_visible(False)
            tick.tick2line.set_visible(False)
            tick.label1.set_visible(False)
            tick.label2.set_visible(False)
        for tick in ax.yaxis.get_major_ticks():
            tick.tick1line.set_visible(False)
            tick.tick2line.set_visible(False)
            tick.label1.set_visible(False)
            tick.label2.set_visible(False)
        im_ratio = delta.shape[0] / delta.shape[1]
        fig.colorbar(image, ax=ax, label="Delta", fraction=0.047 * im_ratio)
        outputs.append(fig)

    # Display in streamlit
    # description.empty()
    results_container.empty()
    with results_container.container():
        st.write(f"Change in projected variables between {year_start} to {year_end}. Machine learning outputs may be unstable.")
        st.write("### Livestock Distribution\nValues displayed are arbitrary units (differences in model confidence of livestock suitability).")
        st.pyplot(outputs[0])
        st.write("### Intermediate Outputs\n#### Crop Distribution\nValues displayed are change in percentage of land covered by cropland.")
        st.pyplot(outputs[1])
        st.write("#### Pasture Distribution\nValues displayed are change in percentage of land covered by pasture.")
        st.pyplot(outputs[2])
    for output in outputs:
        plt.close(output)

if __name__ == "__main__":
    main()